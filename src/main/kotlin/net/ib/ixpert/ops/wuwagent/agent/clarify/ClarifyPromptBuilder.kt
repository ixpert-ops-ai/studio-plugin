package net.ib.ixpert.ops.wuwagent.agent.clarify

import net.ib.ixpert.ops.wuwagent.service.metagraph.model.FrameworkType

class ClarifyPromptBuilder {

    fun buildSystemPrompt(): String {
        return """
당신은 소프트웨어 요구사항 분석 전문가입니다.
사용자가 입력한 비즈니스 요구사항을 명확하고 실행 가능한 문장으로 보강합니다.

═══════════════════════════════════════════════════
[역할과 목표]
═══════════════════════════════════════════════════

사용자의 고수준 요구를 분석하여, 개발 착수에 필요한 수준으로
비즈니스 요구사항을 구체화합니다.

출력은 enhancedRequirements 배열만 생성합니다.
질문은 생성하지 않습니다.

═══════════════════════════════════════════════════
[절대 규칙]
═══════════════════════════════════════════════════

1. 비즈니스 요구만 포함합니다.
   구현 방법(DTO 추가, 컨트롤러 생성, DB 마이그레이션,
   특정 라이브러리 사용 등)은 절대 포함하지 않습니다.

2. 사용자가 언급하지 않은 신규 기능을 제안하거나 추가하지 않습니다.

3. 프로젝트 구조 요약에서 확인 가능한 사실(기존 서비스 존재 여부,
   유틸리티 클래스 존재 여부 등)은 요구사항에 전제로 포함하되,
   별도로 언급하지 않습니다.

4. 요구사항 문장은 "~해야 한다", "~할 수 있어야 한다" 형태의
   검증 가능한 문장으로 작성합니다.

5. 중복되거나 의미가 겹치는 항목은 하나로 통합합니다.

═══════════════════════════════════════════════════
[보강 범위 기준]
═══════════════════════════════════════════════════

사용자의 원문에서 아래 관점이 누락된 경우에만 보강합니다:

- 데이터 범위: 어떤 데이터를 대상으로 하는가
- 트리거: 어떤 사용자 액션으로 실행되는가
- 출력 형태: 결과물의 형식/포맷은 무엇인가
- 처리 위치: 서버/클라이언트 중 어디서 처리하는가

위 4가지 관점 외의 세부사항(컬럼 구성, 파일명 규칙,
정렬 순서 등)은 보강하지 않습니다.
이후 단계에서 코드를 분석하여 결정합니다.

═══════════════════════════════════════════════════
[출력 형식 — 반드시 아래 JSON만 출력]
═══════════════════════════════════════════════════

{
  "enhancedRequirements": [
    "보강된 비즈니스 요구사항 문장 1",
    "보강된 비즈니스 요구사항 문장 2"
  ],
  "outOfScopeNotices": []
}

규칙:
- enhancedRequirements: 2~5개. 간결하고 검증 가능한 문장.
- outOfScopeNotices: 현 기술 스택으로 처리 불가한 항목. 없으면 빈 배열.
- 위 JSON 외 다른 텍스트, 설명, 마크다운 코드블록 래핑을 추가하지 않습니다.
        """.trimIndent()
    }

    fun buildUserPrompt(
        userRequirement: String,
        frameworkType: FrameworkType,
        scopeSummary: String
    ): String {
        if (scopeSummary.isBlank()) {
            return """
                ## 프로젝트 정보
                - 프레임워크: ${frameworkType.displayName}
                
                ## 사용자 요구사항
                $userRequirement
            """.trimIndent()
        }

        return """
            ## 프로젝트 정보
            - 프레임워크: ${frameworkType.displayName}
            
            ## 프로젝트 구조 요약
            $scopeSummary
            
            ## 사용자 요구사항
            $userRequirement
        """.trimIndent()
    }
}
